'use strict';
const assert=require('node:assert/strict'),C=require('./campaign.js'),B=require('./campaign-battle.js');
const s=C.create();s.location='east';
const trial=C.trial(s,"character_rio",'dagger-wood','rightHand');assert(trial);
const b=trial.battle,a=b.units.find(u=>u.id==="character_rio"),target=b.units.find(u=>u.side==='enemy');
a.pos=23;target.pos=26;
let extra=0;for(const u of b.units.filter(u=>u!==a&&u!==target))u.pos=[0,1,8,9][extra++];
const prediction=B.damagePreview(b,a,'action_skill',target.id);
assert.equal(prediction.length,1);
const copy=JSON.parse(JSON.stringify(b)),reference=copy.units.find(u=>u.id===a.id);
reference.pos=B.ambush(copy,reference,copy.units.find(u=>u.id===target.id)).destination;
const attack=B.attackPreview(copy,reference,copy.units.find(u=>u.id===target.id));
assert.equal(prediction[0].damage,attack.damage);assert.equal(prediction[0].base,attack.base);
const hp=target.hp;assert(C.trialAct(trial, 'action_skill',target.id));assert.equal(hp-target.hp,attack.damage);
assert.equal(target.def,2,'current enemy keeps its wooden shield');
assert.equal(a.def,C.stats(s.characters[a.id]).def,'trial uses the current recruit equipment');
console.log(JSON.stringify({test:'ambush equals ordinary attack from landing',weaponContribution:attack.base,ordinaryDamage:attack.damage,ambushDamage:hp-target.hp,DEF:target.def}));
const dual=C.create();dual.location='east';dual.gold=2000;
assert(C.buyGear(dual,"character_merina",'sword-wood','rightHand'));assert(C.buyGear(dual,"character_merina",'staff-wood','leftHand'));
const t=C.trial(dual,"character_merina",'dagger-wood','rightHand'),actor=t.battle.units.find(u=>u.id==="character_merina"),victim=t.battle.units.find(u=>u.side==='enemy');
actor.pos=21;victim.pos=24;extra=0;
for(const u of t.battle.units.filter(u=>u!==actor&&u!==victim))u.pos=[0,1,8,9][extra++];
assert.deepEqual(actor.attackWeapons.map(w=>w.reach),[1,2]);
assert.equal(B.reachFilteredPower(actor,victim).base,0,'original distance does not reach either weapon');
const preview=B.damagePreview(t.battle,actor,'action_skill',victim.id)[0];
assert.equal(preview.base,23+14);assert.equal(preview.weapons.length,2);
const priorHp=victim.hp;assert(C.trialAct(t, 'action_skill',victim.id));
assert.equal(victim.def,2);assert.equal(priorHp-victim.hp,35);
console.log(JSON.stringify({test:'mixed reach 1+2 at original distance 3',weaponContribution:preview.base,ambushDamage:priorHp-victim.hp,weapons:preview.weapons.map(w=>w.itemId)}));
// A completed personal opportunity releases the used grant before the next cast.
assert.equal(B.legal(t.battle,'action_skill',victim.id),false);
assert(C.trialAct(t, 'action_defend'));
victim.def=5;
const reduced=B.damagePreview(t.battle,actor,'action_skill',victim.id)[0],beforeDefHit=victim.hp;
assert.equal(reduced.damage,32);assert(C.trialAct(t, 'action_skill',victim.id));assert.equal(beforeDefHit-victim.hp,32);
console.log(JSON.stringify({test:'same mixed-reach ambush with DEF5',base:reduced.base,previewDamage:reduced.damage,actualDamage:beforeDefHit-victim.hp}));
